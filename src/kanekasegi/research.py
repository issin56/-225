def _ensure_unique_candidate_names(candidates: list[RuleCandidate]) -> list[RuleCandidate]:
    seen: set[str] = set()
    duplicates: set[str] = set()
    for candidate in candidates:
        if candidate.name in seen:
            duplicates.add(candidate.name)
        seen.add(candidate.name)
    if duplicates:
        duplicate_names = ", ".join(sorted(duplicates))
        raise ValueError(f"duplicate candidate names: {duplicate_names}")
    return candidates


def _score_result(result: dict[str, object]) -> float:
    profit = float(result["profit"])
    max_drawdown = max(float(result["max_drawdown"]), 1.0)
    win_rate = float(result["win_rate"])
    profitable_month_ratio = float(result["profitable_month_ratio"])
    average_monthly_pnl = float(result["average_monthly_pnl"])
    return round((profit / max_drawdown) * 900 + win_rate * 120 + profitable_month_ratio * 140 + average_monthly_pnl / 1000, 4)


def _checkpoint_payload(
    config_path: str,
    results: list[dict[str, object]],
    ranked: list[dict[str, object]],
    *,
    min_trades: int,
    top: int,
    candidate_names: list[str],
) -> dict[str, object]:
    return {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "config_path": config_path,
        "runs": len(results),
        "min_trades_filter": min_trades,
        "candidate_names": candidate_names,
        "top": ranked[:top],
        "all_results": results,
    }


def _write_checkpoint(checkpoint_dir: str | Path, payload: dict[str, object], *, batch_name: str | None = None) -> str:
    target_dir = Path(checkpoint_dir)
    target_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    name = batch_name or "nk225micro-research"
    checkpoint_path = target_dir / f"{timestamp}-{name}.json"
    checkpoint_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return str(checkpoint_path)


